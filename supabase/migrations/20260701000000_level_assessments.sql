-- Migration: Level Assessments (Placement & Progress Checks)
-- Supports initial student placement test and recurring progress assessments requested by teachers.

-- 1. Create table level_assessments
CREATE TABLE IF NOT EXISTS public.level_assessments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    student_id UUID NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
    teacher_id UUID REFERENCES public.psychologists(id) ON DELETE SET NULL,
    assessment_type TEXT NOT NULL CHECK (assessment_type IN ('INITIAL_PLACEMENT', 'PROGRESS_CHECK')) DEFAULT 'INITIAL_PLACEMENT',
    status TEXT NOT NULL CHECK (status IN ('PENDING', 'IN_PROGRESS', 'COMPLETED')) DEFAULT 'PENDING',
    
    -- Dynamic test payload generated by AI
    test_content JSONB DEFAULT '{}'::jsonb,
    
    -- Student submitted responses
    student_answers JSONB DEFAULT '{}'::jsonb,
    
    -- Audio reading recording
    audio_url TEXT,
    audio_duration_seconds NUMERIC DEFAULT 0,
    
    -- Scores & Level
    pronunciation_score NUMERIC DEFAULT 0,
    grammar_score NUMERIC DEFAULT 0,
    reading_score NUMERIC DEFAULT 0,
    overall_score NUMERIC DEFAULT 0,
    assigned_level TEXT CHECK (assigned_level IN ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')),
    
    -- Detailed pedagogical evaluation report
    evaluation_report JSONB DEFAULT '{}'::jsonb,
    
    requested_by_teacher_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- 2. Indexes for fast retrieval
CREATE INDEX IF NOT EXISTS idx_level_assessments_student ON public.level_assessments(student_id);
CREATE INDEX IF NOT EXISTS idx_level_assessments_teacher ON public.level_assessments(teacher_id);
CREATE INDEX IF NOT EXISTS idx_level_assessments_status ON public.level_assessments(status);

-- 3. Ensure student_level column on patients
ALTER TABLE public.patients ADD COLUMN IF NOT EXISTS student_level TEXT;

-- 4. Enable RLS
ALTER TABLE public.level_assessments ENABLE ROW LEVEL SECURITY;

-- Policy: Teachers can view assessments for their own students
CREATE POLICY "Teachers can view level assessments of their students"
ON public.level_assessments
FOR SELECT
USING (
    teacher_id = auth.uid() OR
    student_id IN (
        SELECT id FROM public.patients WHERE psychologist_id = auth.uid()
    )
);

-- Policy: Teachers can create/request assessments for their students
CREATE POLICY "Teachers can create level assessments"
ON public.level_assessments
FOR INSERT
WITH CHECK (
    teacher_id = auth.uid() OR
    student_id IN (
        SELECT id FROM public.patients WHERE psychologist_id = auth.uid()
    )
);

-- Policy: Teachers can update assessments
CREATE POLICY "Teachers can update level assessments"
ON public.level_assessments
FOR UPDATE
USING (
    teacher_id = auth.uid() OR
    student_id IN (
        SELECT id FROM public.patients WHERE psychologist_id = auth.uid()
    )
);

-- Policy: Students can view their own assessments
CREATE POLICY "Students can view their own level assessments"
ON public.level_assessments
FOR SELECT
USING (
    student_id IN (
        SELECT id FROM public.patients WHERE user_id = auth.uid()
    )
);

-- Policy: Students can update their own assessment (to submit answers and audio)
CREATE POLICY "Students can update their own level assessments"
ON public.level_assessments
FOR UPDATE
USING (
    student_id IN (
        SELECT id FROM public.patients WHERE user_id = auth.uid()
    )
);

-- Policy: Students can insert initial placement assessment
CREATE POLICY "Students can insert their own initial placement assessment"
ON public.level_assessments
FOR INSERT
WITH CHECK (
    student_id IN (
        SELECT id FROM public.patients WHERE user_id = auth.uid()
    )
);

-- 5. Create storage bucket for student assessment audio recordings
INSERT INTO storage.buckets (id, name, public) 
VALUES ('student-assessments', 'student-assessments', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Storage policies: anyone authenticated can upload to student-assessments
CREATE POLICY "Authenticated users can upload assessment audio"
ON storage.objects FOR INSERT
TO authenticated
WITH CHECK (bucket_id = 'student-assessments');

CREATE POLICY "Public read on student assessment audio"
ON storage.objects FOR SELECT
TO public
USING (bucket_id = 'student-assessments');
